#!/usr/bin/env python3
"""Turns the knowledge-base documents (data/knowledge_base/*.md) into passages for the RAG demo.

Each "## n. Heading" section becomes one passage. Output: demos/rag_corpus.js
"""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
KB = os.path.join(HERE, "data", "knowledge_base")

# file → (short id prefix, short name shown in the demo, icon)
DOCS = {
    "osce_regulations_2026.md": ("osce", "OSCE regulations 2026–27", "📋"),
    "clinical_placement_handbook.md": ("place", "Placement handbook", "🏥"),
    "hand_hygiene_course_notes.md": ("hyg", "Hand hygiene notes", "🧼"),
    "diabetes_course_notes.md": ("diab", "Diabetes notes", "🩸"),
}


def passages():
    out = []
    for fname, (prefix, short, icon) in DOCS.items():
        with open(os.path.join(KB, fname), encoding="utf-8") as f:
            md = f.read()
        for m in re.finditer(r"^## (\d+)\. (.+?)\n\n(.+?)(?=\n## |\Z)", md, re.S | re.M):
            num, heading, body = m.group(1), m.group(2).strip(), " ".join(m.group(3).split())
            out.append({"id": f"{prefix}-{num}", "doc": short, "icon": icon,
                        "section": f"§{num} {heading}", "text": body})
    return out


def main():
    ps = passages()
    path = os.path.join(HERE, "demos", "rag_corpus.js")
    with open(path, "w", encoding="utf-8") as f:
        f.write("// Generated by make_corpus.py from data/knowledge_base/*.md: do not edit by hand.\n")
        f.write("const CORPUS = " + json.dumps(ps, ensure_ascii=False, indent=1) + ";\n")
    print(f"→ {path} ({len(ps)} passages)")


if __name__ == "__main__":
    main()
